-- 03_core_tables.sql
-- Builds typed, cleaned tables in core from the raw staging tables.
--   raw.orig -> core.orig  (one row per loan, PK loan_seq_no)
--   raw.perf -> core.perf  (one row per loan per month, PK loan_seq_no + period, FK to core.orig)
-- Cleaning rules:
--   sentinel codes (9999, 999, 99, 9, 7, 000) -> NULL
--   YYYYMM text -> DATE (first of month)
--   Y/N flags -> BOOLEAN; Y/NULL flags kept as TEXT
--   delinquency_status kept as text; delinquency_months derived (RA, XX -> NULL)
--   non-numeric net_sale_proceeds -> NULL
-- Safe to rerun: drops and rebuilds both tables. Requires 01 and 02 to have run.
-- Run from the repo root:
--   psql -h localhost -U mikhail -d freddie -v ON_ERROR_STOP=1 -f sql/03_core_tables.sql

DROP TABLE IF EXISTS core.perf;
DROP TABLE IF EXISTS core.orig;

CREATE TABLE core.orig(
    credit_score INTEGER,
    first_payment_date DATE,
    first_time_homebuyer BOOLEAN,
    maturity_date DATE,
    msa TEXT,
    mi_pct INTEGER,
    num_units INTEGER,
    occupancy_status TEXT,
    orig_cltv INTEGER,
    orig_dti INTEGER,
    orig_upb NUMERIC(14,2),
    orig_ltv INTEGER,
    orig_interest_rate NUMERIC(6,3),
    channel TEXT,
    ppm_flag BOOLEAN,
    amortization_type TEXT,
    property_state TEXT,
    property_type TEXT,
    postal_code TEXT,
    loan_seq_no TEXT PRIMARY KEY,
    loan_purpose TEXT,
    orig_loan_term INTEGER,
    num_borrowers INTEGER,
    seller_name TEXT,
    super_conforming_flag BOOLEAN,
    pre_harp_loan_seq_no TEXT,
    program_indicator TEXT,
    harp_indicator BOOLEAN,
    valuation_method INTEGER,
    io_indicator BOOLEAN,
    vantagescore4 INTEGER
);
INSERT INTO core.orig (credit_score,
                       first_payment_date,
                       first_time_homebuyer,
                       maturity_date,
                       msa,
                       mi_pct,
                       num_units,
                       occupancy_status,
                       orig_cltv,
                       orig_dti,
                       orig_upb,
                       orig_ltv,
                       orig_interest_rate,
                       channel,
                       ppm_flag,
                       amortization_type,
                       property_state,
                       property_type,
                       postal_code,
                       loan_seq_no,
                       loan_purpose,
                       orig_loan_term,
                       num_borrowers,
                       seller_name,
                       super_conforming_flag,
                       pre_harp_loan_seq_no,
                       program_indicator,
                       harp_indicator,
                       valuation_method,
                       io_indicator,
                       vantagescore4)
SELECT NULLIF(credit_score, '9999')::int,
       to_date(first_payment_date, 'YYYYMM'),
       CASE first_time_homebuyer WHEN 'Y' THEN true WHEN 'N' THEN false END,
       to_date(maturity_date, 'YYYYMM'),
       msa,
       NULLIF(mi_pct, '999')::int,
       NULLIF(num_units, '99')::int,
       NULLIF(occupancy_status, '9'),
       NULLIF(orig_cltv, '999')::int,
       NULLIF(orig_dti, '999')::int,
       orig_upb::numeric(14,2),
       NULLIF(orig_ltv, '999')::int,
       orig_interest_rate::numeric(6,3),
       NULLIF(channel, '9'),
       CASE ppm_flag WHEN 'Y' THEN true WHEN 'N' THEN false END,
       amortization_type,
       property_state,
       NULLIF(property_type, '99'),
       postal_code,
       loan_seq_no,
       NULLIF(loan_purpose, '9'),
       orig_loan_term::int,
       NULLIF(num_borrowers, '99')::int,
       seller_name,
       CASE super_conforming_flag WHEN 'Y' THEN true WHEN 'N' THEN false END,
       pre_harp_loan_seq_no,
       program_indicator,
       CASE harp_indicator WHEN 'Y' THEN true WHEN 'N' THEN false END,
       NULLIF(valuation_method, '7')::int,
       CASE io_indicator WHEN 'Y' THEN true WHEN 'N' THEN false END,
       NULLIF(vantagescore4, '9999')::int
FROM raw.orig;

CREATE TABLE core.perf (
    loan_seq_no                 TEXT NOT NULL REFERENCES core.orig (loan_seq_no),
    period                      DATE NOT NULL,
    current_upb                 NUMERIC(14,2),
    delinquency_status          TEXT,
    delinquency_months          INTEGER,
    loan_age                    INTEGER,
    remaining_months            INTEGER,
    defect_settlement_date      DATE,
    modification_flag           TEXT,
    zero_balance_code           TEXT,
    zero_balance_date           DATE,
    current_interest_rate       NUMERIC(6,3),
    current_non_int_upb         NUMERIC(14,2),
    ddlpi                       DATE,
    mi_recoveries               NUMERIC(14,2),
    net_sale_proceeds           NUMERIC(14,2),
    non_mi_recoveries           NUMERIC(14,2),
    total_expenses              NUMERIC(14,2),
    legal_costs                 NUMERIC(14,2),
    maint_preservation_costs    NUMERIC(14,2),
    taxes_insurance             NUMERIC(14,2),
    misc_expenses               NUMERIC(14,2),
    actual_loss                 NUMERIC(14,2),
    cumulative_mod_cost         NUMERIC(14,2),
    step_rate_indicator         BOOLEAN,
    payment_deferral_flag       TEXT,
    eltv                        INTEGER,
    zero_balance_removal_upb    NUMERIC(14,2),
    delinquent_accrued_interest NUMERIC(14,2),
    disaster_flag               TEXT,
    borrower_assistance_plan    TEXT,
    current_period_mod_cost     NUMERIC(14,2),
    current_int_upb             NUMERIC(14,2),
    mi_cancellation_indicator   TEXT,
    servicer_name               TEXT,
    bankruptcy_cramdown_costs   NUMERIC(14,2),
    PRIMARY KEY (loan_seq_no, period)
);

INSERT INTO core.perf (
    loan_seq_no, period, current_upb, delinquency_status, delinquency_months,
    loan_age, remaining_months, defect_settlement_date, modification_flag,
    zero_balance_code, zero_balance_date, current_interest_rate, current_non_int_upb,
    ddlpi, mi_recoveries, net_sale_proceeds, non_mi_recoveries, total_expenses,
    legal_costs, maint_preservation_costs, taxes_insurance, misc_expenses,
    actual_loss, cumulative_mod_cost, step_rate_indicator, payment_deferral_flag,
    eltv, zero_balance_removal_upb, delinquent_accrued_interest, disaster_flag,
    borrower_assistance_plan, current_period_mod_cost, current_int_upb,
    mi_cancellation_indicator, servicer_name, bankruptcy_cramdown_costs
)
SELECT
    loan_seq_no,
    to_date(period, 'YYYYMM'),
    current_upb::numeric(14,2),
    delinquency_status,
    CASE WHEN delinquency_status ~ '^\d+$' THEN delinquency_status::int END,
    loan_age::int,
    remaining_months::int,
    to_date(defect_settlement_date, 'YYYYMM'),
    modification_flag,
    zero_balance_code,
    to_date(zero_balance_date, 'YYYYMM'),
    current_interest_rate::numeric(6,3),
    current_non_int_upb::numeric(14,2),
    to_date(ddlpi, 'YYYYMM'),
    mi_recoveries::numeric(14,2),
    CASE WHEN net_sale_proceeds ~ '^-?\d+(\.\d+)?$' THEN net_sale_proceeds::numeric(14,2) END,
    non_mi_recoveries::numeric(14,2),
    total_expenses::numeric(14,2),
    legal_costs::numeric(14,2),
    maint_preservation_costs::numeric(14,2),
    taxes_insurance::numeric(14,2),
    misc_expenses::numeric(14,2),
    actual_loss::numeric(14,2),
    cumulative_mod_cost::numeric(14,2),
    CASE step_rate_indicator WHEN 'Y' THEN true WHEN 'N' THEN false END,
    payment_deferral_flag,
    NULLIF(eltv, '999')::int,
    zero_balance_removal_upb::numeric(14,2),
    delinquent_accrued_interest::numeric(14,2),
    disaster_flag,
    borrower_assistance_plan,
    current_period_mod_cost::numeric(14,2),
    current_int_upb::numeric(14,2),
    NULLIF(mi_cancellation_indicator, '7'),
    trim(servicer_name),
    bankruptcy_cramdown_costs::numeric(14,2)
FROM raw.perf;

CREATE INDEX perf_period_idx ON core.perf (period);

ANALYZE core.orig;
ANALYZE core.perf;